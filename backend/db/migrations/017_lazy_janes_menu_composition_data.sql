  INSERT INTO menu_item_ingredients (
    menu_item_id,
    ingredient_id,
    can_remove,
    can_extra,
    extra_price,
    sort_order
  )
  SELECT
    item.id,
    ingredient.id,
    seed.can_remove,
    seed.can_extra,
    seed.extra_price,
    seed.sort_order
  FROM seed_menu_components seed
  JOIN menu_groups group_record
    ON group_record.name = seed.group_name
  JOIN menu_categories category
    ON category.group_id = group_record.id
   AND category.name = seed.category_name
  JOIN menu_items item
    ON item.category_id = category.id
   AND item.name = seed.item_name
   AND item.is_modifier = false
  JOIN ingredients ingredient
    ON lower(ingredient.name) = lower(seed.ingredient_name)
  ON CONFLICT (menu_item_id, ingredient_id) DO UPDATE
  SET
    can_remove = EXCLUDED.can_remove,
    can_extra = EXCLUDED.can_extra,
    extra_price = EXCLUDED.extra_price,
    sort_order = EXCLUDED.sort_order,
    updated_at = now();


