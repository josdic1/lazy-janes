  JOIN menu_items item
    ON item.category_id = category.id
   AND item.name = seed.item_name
   AND item.is_modifier = false
  ON CONFLICT (menu_item_id, (lower(label))) DO UPDATE
  SET
    min_selections = EXCLUDED.min_selections,
    max_selections = EXCLUDED.max_selections,
    sort_order = EXCLUDED.sort_order,
    is_active = true,
    updated_at = now();

  INSERT INTO menu_choice_options (
    choice_group_id,
    label,
    ingredient_id,
    price_adjustment,
    sort_order,
    is_default
  )
  SELECT
    choice_group.id,
    seed.option_label,
    ingredient.id,
    seed.price_adjustment,
    seed.option_sort_order,
    seed.is_default
  FROM seed_menu_choices seed
  JOIN menu_groups group_record
    ON group_record.name = seed.group_name
  JOIN menu_categories category
    ON category.group_id = group_record.id
   AND category.name = seed.category_name
  JOIN menu_items item
    ON item.category_id = category.id
   AND item.name = seed.item_name
   AND item.is_modifier = false
  JOIN menu_choice_groups choice_group
    ON choice_group.menu_item_id = item.id
   AND lower(choice_group.label) = lower(seed.choice_label)
  LEFT JOIN ingredients ingredient
    ON seed.ingredient_name IS NOT NULL
   AND lower(ingredient.name) = lower(seed.ingredient_name)
  ON CONFLICT (choice_group_id, (lower(label))) DO UPDATE
  SET
    ingredient_id = EXCLUDED.ingredient_id,
    price_adjustment = EXCLUDED.price_adjustment,
    sort_order = EXCLUDED.sort_order,
    is_default = EXCLUDED.is_default,
    is_active = true,
    updated_at = now();

  -- Legacy choice rows were migrated before this canonical ingredient catalog
  -- existed. Link safe exact-name matches now, plus the two unambiguous side
  -- aliases used by the original menu.
  UPDATE menu_choice_options option_record
  SET
    ingredient_id = ingredient.id,
    updated_at = now()
  FROM ingredients ingredient
  WHERE option_record.ingredient_id IS NULL
    AND lower(ingredient.name) = lower(
      CASE lower(option_record.label)
        WHEN 'two vegetables' THEN 'Vegetables'
        WHEN 'side of spaghetti' THEN 'Spaghetti'
        ELSE option_record.label
      END
    );
END;
